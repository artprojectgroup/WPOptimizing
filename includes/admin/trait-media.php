	/**
	 * Drop given attachment IDs from the cached media report's unused section in
	 * place (no re-scan), so rows marked as known disappear immediately. Nothing is
	 * deleted from disk — this only updates the cached view and counts.
	 *
	 * @param int[] $ids Attachment IDs to remove from the unused list.
	 * @return void
	 */
	protected function prune_unused_report_ids( array $ids ) {
		$ids = array_values( array_filter( array_map( 'intval', $ids ) ) );
		if ( empty( $ids ) ) {
			return;
		}
		$report = wpoptimizing_media_report_get();
		if ( ! is_array( $report ) || ! isset( $report['unused']['sample'] ) ) {
			return;
		}
		$drop                       = array_flip( $ids );
		$before                     = count( (array) $report['unused']['sample'] );
		$report['unused']['sample'] = array_values(
			array_filter(
				(array) $report['unused']['sample'],
				static function ( $r ) use ( $drop ) {
					return ! isset( $drop[ (int) ( $r['id'] ?? 0 ) ] );
				}
			)
		);
		$removed                    = $before - count( (array) $report['unused']['sample'] );
		$report['unused']['count']  = max( 0, (int) ( $report['unused']['count'] ?? 0 ) - $removed );
		wpoptimizing_media_report_save( $report );
		if ( function_exists( 'wpoptimizing_store_media_stats' ) ) {
			wpoptimizing_store_media_stats( $report );
		}
	}



	/**
	 * Whether a duplicate set read from the report may still be merged, judged now: every
	 * member on its own file and not a WPML translation of another (see
	 * WPOPT_Media_Deduper::group_is_mergeable()), and every duplicate still byte-identical to
	 * the kept file — a file replaced since the analysis is no longer a duplicate.
	 *
	 * @param int   $keep_id  Kept attachment.
	 * @param int[] $dupe_ids Duplicates.
	 * @return bool
	 */
	protected function dedupe_set_still_valid( $keep_id, array $dupe_ids ) {
		global $wpdb;
		$files = array();
		foreach ( array_merge( array( (int) $keep_id ), $dupe_ids ) as $id ) {
			$files[ (int) $id ] = (string) get_post_meta( (int) $id, '_wp_attached_file', true );
		}

		$trids = array();
		$table = $wpdb->prefix . 'icl_translations';
		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQLPlaceholders.ReplacementsWrongNumber
		if ( $table === (string) $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $wpdb->esc_like( $table ) ) ) ) {
			$ids  = array_keys( $files );
			$rows = $wpdb->get_results(
				$wpdb->prepare(
					'SELECT element_id, trid FROM %i WHERE element_type = %s AND element_id IN (' . implode( ',', array_fill( 0, count( $ids ), '%d' ) ) . ')',
					array_merge( array( $table, 'post_attachment' ), $ids )
				),
				ARRAY_A
			);
			if ( '' !== (string) $wpdb->last_error ) {
				return false;
			}
			foreach ( (array) $rows as $row ) {
				$trids[ (int) $row['element_id'] ] = (int) $row['trid'];
			}
		}
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQLPlaceholders.ReplacementsWrongNumber
		if ( ! WPOPT_Media_Deduper::group_is_mergeable( $files, $trids ) ) {
			return false;
		}

		$uploads = wp_get_upload_dir();
		$base    = ! empty( $uploads['basedir'] ) ? trailingslashit( (string) $uploads['basedir'] ) : '';
		$keep    = ( '' !== $base && is_file( $base . $files[ (int) $keep_id ] ) ) ? md5_file( $base . $files[ (int) $keep_id ] ) : false;
		if ( false === $keep ) {
			return false;
		}
		foreach ( $dupe_ids as $did ) {
			$abs = $base . $files[ (int) $did ];
			if ( ! is_file( $abs ) || md5_file( $abs ) !== $keep ) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Remove just-deleted media orphan files ("media::…" identifiers) from the
	 * cached report in place so the Media tab updates without a full re-scan.
	 * No-op for non-media filesystem paths.
	 *
	 * @param string[] $ids Deleted identifiers (delete_fs_paths values).
	 * @return void
	 */
	protected function prune_media_report_files( array $ids ) {
		$report = wpoptimizing_media_report_get();
		if ( ! is_array( $report ) ) {
			return;
		}
		$uploads      = wp_get_upload_dir();
		$content_base = wp_normalize_path( trailingslashit( WP_CONTENT_DIR ) );
		$uploads_base = ! empty( $uploads['basedir'] ) ? wp_normalize_path( trailingslashit( (string) $uploads['basedir'] ) ) : '';
		$prefix       = ( '' !== $uploads_base && 0 === strpos( $uploads_base, $content_base ) ) ? trim( substr( $uploads_base, strlen( $content_base ) ), '/' ) : '';

		$files = array();
		foreach ( $ids as $id ) {
			$id = (string) $id;
			if ( 0 !== strpos( $id, 'media::' ) ) {
				continue;
			}
			$rel = ltrim( substr( $id, strlen( 'media::' ) ), '/' ); // wp-content-relative, e.g. uploads/foo.jpg
			if ( '' !== $prefix && 0 === strpos( $rel, $prefix . '/' ) ) {
				$rel = substr( $rel, strlen( $prefix ) + 1 );
			}
			if ( '' !== $rel ) {
				$files[] = $rel;
			}
		}
		if ( empty( $files ) ) {
			return;
		}
		if ( function_exists( 'wpoptimizing_load_engine' ) ) {
			wpoptimizing_load_engine();
		}
		if ( ! class_exists( 'WPOPT_Media_Analyzer' ) ) {
			return;
		}
		$report = WPOPT_Media_Analyzer::prune_files_from_report( $report, $files );
		wpoptimizing_media_report_save( $report );
		if ( function_exists( 'wpoptimizing_store_media_stats' ) ) {
			wpoptimizing_store_media_stats( $report );
		}
	}
