		if ( is_array( $report ) && ! empty( $report['generated_at'] ) ) {
			echo ' ' . esc_html( sprintf( /* translators: %s: date */ __( 'Last analyzed: %s', 'wpoptimizing' ), wp_date( get_option( 'date_format' ) . ' ' . get_option( 'time_format' ), (int) $report['generated_at'] ) ) );
		}
		echo '</p>';

		if ( ! is_array( $report ) ) {
			echo '<div class="notice notice-info inline wpopt-notice"><p>' . esc_html__( 'Run “Analyze now” to see orphaned and duplicate media here.', 'wpoptimizing' ) . '</p></div>';
			return;
		}

		$of  = $report['orphan_files'] ?? array(
			'count'      => 0,
			'size_bytes' => 0,
			'sample'     => array(),
		);
		$ot  = $report['orphan_thumbs'] ?? array(
			'count'      => 0,
			'size_bytes' => 0,
			'sample'     => array(),
		);
		$oth = $report['other_files'] ?? array(
			'count'      => 0,
			'size_bytes' => 0,
			'sample'     => array(),
		);
		$dup = $report['duplicates'] ?? array(
			'groups'             => 0,
			'extra'              => 0,
			'reclaimable_bytes'  => 0,
			'attachments_hashed' => 0,
			'partial'            => false,
			'sample'             => array(),
		);
		$un  = $report['unused'] ?? array(
			'count'      => 0,
			'size_bytes' => 0,
			'partial'    => false,
			'sample'     => array(),
		);

		/*
		 * UNA SOLA DEFINICIÓN DE «el escaneo se quedó corto». La respuesta la da el ayudante,
		 * que es el que también usa el endpoint de lotes; aquí se leía `$un['partial']` a mano,
		 * o sea dos copias de la misma pregunta que pueden separarse en cuanto una cambie. Es
		 * una lectura de transitorio, así que se pide una vez y se reutiliza.
		 */
		$un_partial = function_exists( 'wpoptimizing_media_unused_scan_is_partial' )
			? wpoptimizing_media_unused_scan_is_partial()
			: ! empty( $un['partial'] );

		// Info cards. Flex-wrap so cards spread evenly and fill each row (no empty
		// columns / lopsided second line like grid auto-fill produced).
		echo '<div class="wpopt-media-cards">';
		$cards = array(
			array( __( 'Files scanned', 'wpoptimizing' ), number_format_i18n( (int) ( $report['files_scanned'] ?? 0 ) ), '#2271b1' ),
			array( __( 'Orphan files', 'wpoptimizing' ), number_format_i18n( (int) $of['count'] ) . ' · ' . size_format( (int) $of['size_bytes'], 1 ), (int) $of['count'] > 0 ? '#bd8600' : '#2271b1' ),
			array( __( 'Orphan thumbnails', 'wpoptimizing' ), number_format_i18n( (int) $ot['count'] ) . ' · ' . size_format( (int) $ot['size_bytes'], 1 ), (int) $ot['count'] > 0 ? '#bd8600' : '#2271b1' ),
			array( __( 'Other files', 'wpoptimizing' ), number_format_i18n( (int) $oth['count'] ) . ' · ' . size_format( (int) $oth['size_bytes'], 1 ), (int) $oth['count'] > 0 ? '#787c82' : '#2271b1' ),
			array(
				/* translators: card showing N duplicate sets reclaiming X space. */
				_n( 'Duplicate set', 'Duplicate sets', (int) $dup['groups'], 'wpoptimizing' ),
				number_format_i18n( (int) $dup['groups'] ) . ( (int) $dup['reclaimable_bytes'] > 0 ? ' · ' . size_format( (int) $dup['reclaimable_bytes'], 1 ) : '' ),
				(int) $dup['groups'] > 0 ? '#bd8600' : '#2271b1',
			),
			array(
				__( 'Potentially unused', 'wpoptimizing' ),
				number_format_i18n( (int) $un['count'] ) . ( (int) $un['size_bytes'] > 0 ? ' · ' . size_format( (int) $un['size_bytes'], 1 ) : '' ),
				(int) $un['count'] > 0 ? '#bd8600' : '#2271b1',
			),
		);
		foreach ( $cards as $c ) {
			echo '<div class="wpopt-card wpopt-card-centered">';
			$num_cls = array(
				'#2271b1' => 'is-info',
				'#bd8600' => 'is-warn',
				'#787c82' => 'is-muted',
			);
			$cls     = $num_cls[ strtolower( (string) $c[2] ) ] ?? 'is-info';
			echo '<div class="wpopt-card-num wpopt-nowrap ' . esc_attr( $cls ) . '">' . esc_html( $c[1] ) . '</div>';
			echo '<div class="wpopt-card-label">' . esc_html( $c[0] ) . '</div>';
			echo '</div>';
		}
		echo '</div>';

		if ( ! empty( $report['truncated'] ) ) {
			echo '<div class="notice notice-warning inline wpopt-notice"><p>' . esc_html__( 'The scan hit its file limit; results are partial.', 'wpoptimizing' ) . '</p></div>';
		}
		if ( ! empty( $dup['partial'] ) ) {
			echo '<div class="notice notice-info inline wpopt-notice"><p>' . esc_html( sprintf( /* translators: %s: number of attachments compared */ __( 'Duplicate detection is partial: %s of the media items that share their size with another one were compared (disk read limit).', 'wpoptimizing' ), number_format_i18n( (int) $dup['attachments_hashed'] ) ) ) . '</p></div>';
		}

		// "Potentially unused attachments" is rendered as its own media subsection
		// below (msec=unused), using the standard list table with search + paging.

		$can_delete = true;

		// Map the uploads dir to a wp-content-relative prefix so orphans can be
		// deleted through the existing FS pipeline (backup + delete). Empty when
		// uploads live outside wp-content → deletion is then unavailable.
		$uploads       = wp_get_upload_dir();
		$content_base  = wp_normalize_path( trailingslashit( WP_CONTENT_DIR ) );
		$uploads_base  = ! empty( $uploads['basedir'] ) ? wp_normalize_path( trailingslashit( (string) $uploads['basedir'] ) ) : '';
		$delete_prefix = ( '' !== $uploads_base && 0 === strpos( $uploads_base, $content_base ) ) ? substr( $uploads_base, strlen( $content_base ) ) : '';
		$baseurl       = isset( $uploads['baseurl'] ) ? (string) $uploads['baseurl'] : '';

		// Shared lightbox modal for image previews.
		$this->render_media_modal();

		// Subsection navigation (WP-native subsubsub) so the tables aren't stacked.
		$msec = isset( $_GET['msec'] ) ? sanitize_key( wp_unslash( $_GET['msec'] ) ) : 'files'; // phpcs:ignore WordPress.Security.NonceVerification.Recommended
		if ( ! in_array( $msec, array( 'files', 'thumbs', 'other', 'renamed', 'duplicates', 'unused', 'optimize', 'heavy', 'trash', 'audit' ), true ) ) {
			$msec = 'files';
		}
		/*
		 * SEIS ENTRADAS, NO DIEZ. Archivos huérfanos, Miniaturas huérfanas y Otros archivos son lo
		 * mismo —ficheros sin registro en la base de datos— separados por clase, así que van en
		 * una entrada con su filtro, como Resultados del análisis. Optimización e Imágenes más
		 * pesadas son el análisis y su lista por imagen. Y las copias que deja Media File Renamer
		 * viven en la Auditoría, junto a los tamaños con nombre anterior que deja el mismo
		 * plugin. Las claves antiguas siguen funcionando: los enlaces guardados no se rompen.
		 */
		$orphan_keys = array( 'files', 'thumbs', 'other' );
		echo '<ul class="subsubsub wpopt-subsubsub">';
		$this->media_menu_link( 'files', __( 'Orphans', 'wpoptimizing' ), $msec, (int) $of['count'] + (int) $ot['count'] + (int) $oth['count'], $orphan_keys );
		echo ' | ';
		$this->media_menu_link( 'duplicates', __( 'Duplicate sets', 'wpoptimizing' ), $msec, (int) $dup['groups'] );
		echo ' | ';
		$this->media_menu_link( 'unused', __( 'Unused attachments', 'wpoptimizing' ), $msec, (int) $un['count'] );
		echo ' | ';
		$this->media_menu_link( 'optimize', __( 'Image optimization', 'wpoptimizing' ), $msec, 0, array( 'optimize', 'heavy' ) );
		echo ' | ';
		$this->media_menu_link( 'trash', __( 'Trash', 'wpoptimizing' ), $msec, $this->media_trash_group_count() );
		echo ' | ';
		$this->media_menu_link( 'audit', __( 'Library audit', 'wpoptimizing' ), $msec, 0, array( 'audit', 'renamed' ) );
		echo '</ul><br class="clear" />';

		// Read-only audit — its own self-contained subsection, nothing shared with the tables.
		// `renamed` is its old address: the renamed-original copies are a block inside it now.
		if ( 'audit' === $msec || 'renamed' === $msec ) {
			// The library audit is Pro (23/10/2026): Lite has only the note, Pro without a license the lock.
			$audit_pro = false;
			if ( ! $audit_pro ) {
				$audit_note = __( 'The media library audit (stranded and competing files, leftover sizes, downloadable dumps and logs, and the uploads protection) is not included in this plugin.', 'wpoptimizing' );
				$this->render_pro_note( $audit_note );
			}
			return;
		}

		if ( 'optimize' === $msec || 'heavy' === $msec ) {
			$this->render_media_chips(
				array(
					'optimize' => array( __( 'Summary', 'wpoptimizing' ), 'info', null ),
					'heavy'    => array( __( 'Heaviest images', 'wpoptimizing' ), 'info', null ),
				),
				$msec,
				__( 'Image optimization views', 'wpoptimizing' )
			);
			if ( 'optimize' === $msec ) {
				$this->render_image_optimization();
			} else {
				$this->render_image_detective();
			}
			return;
		}

		// Media trash: recover files deleted from the media sections (reuses the backup engine).
		if ( 'trash' === $msec ) {
			$this->render_media_trash();
			return;
		}

		if ( in_array( $msec, $orphan_keys, true ) ) {
			$this->render_media_chips(
				array(
					'files'  => array( __( 'Orphan files', 'wpoptimizing' ), 'warn', (int) $of['count'] ),
					'thumbs' => array( __( 'Orphan thumbnails', 'wpoptimizing' ), 'safe', (int) $ot['count'] ),
					'other'  => array( __( 'Other files', 'wpoptimizing' ), 'risk', (int) $oth['count'] ),
				),
				$msec,
				__( 'Filter the orphans by kind', 'wpoptimizing' )
			);
		}

		// Description of the active subsection (uniform across all of them).
		$this->render_media_subsection_description( $msec );

		// Totals for the active subsection, shown as two stat boxes under the
		// description (same wpopt-kpi component as the rest of the UI), so the count
		// and reclaimable size are visible at a glance without leaving the section.
		$sub_totals = array(
			'files'      => array( (int) $of['count'], (int) $of['size_bytes'], false ),
			'thumbs'     => array( (int) $ot['count'], (int) $ot['size_bytes'], false ),
			'other'      => array( (int) $oth['count'], (int) $oth['size_bytes'], false ),
			'duplicates' => array( (int) $dup['groups'], (int) $dup['reclaimable_bytes'], true ),
			'unused'     => array( (int) $un['count'], (int) $un['size_bytes'], false ),
		);
		if ( isset( $sub_totals[ $msec ] ) && $sub_totals[ $msec ][0] > 0 ) {
			list( $t_count, $t_bytes, $t_reclaim ) = $sub_totals[ $msec ];
			$count_label                           = $t_reclaim ? _n( 'Duplicate set', 'Duplicate sets', $t_count, 'wpoptimizing' ) : __( 'Items', 'wpoptimizing' );
			$size_label                            = $t_reclaim ? __( 'Reclaimable', 'wpoptimizing' ) : __( 'Total size', 'wpoptimizing' );
			echo '<div class="wpopt-kpi-grid wpopt-section-totals">';
			printf(
				'<div class="wpopt-kpi"><div class="wpopt-kpi-num is-info">%1$s</div><div class="wpopt-kpi-label">%2$s</div></div>',
				esc_html( number_format_i18n( $t_count ) ),
				esc_html( $count_label )
			);
			printf(
				'<div class="wpopt-kpi"><div class="wpopt-kpi-num is-%1$s">%2$s</div><div class="wpopt-kpi-label">%3$s</div></div>',
				esc_attr( $t_bytes > 0 ? 'warn' : 'info' ),
				esc_html( size_format( $t_bytes, 1 ) ),
				esc_html( $size_label )
			);
			echo '</div>';
		}

		// Per-page is shared across media subsections.
		$media_pp   = isset( $_GET['media_pp'] ) ? max( 25, (int) $_GET['media_pp'] ) : 50; // phpcs:ignore WordPress.Security.NonceVerification.Recommended
		$media_tipo = isset( $_GET['media_tipo'] ) ? sanitize_key( wp_unslash( $_GET['media_tipo'] ) ) : 'all'; // phpcs:ignore WordPress.Security.NonceVerification.Recommended

		if ( 'unused' === $msec ) {
			// Potentially-unused attachments: read-only, heuristic. Surfaced for
			// MANUAL review (references can hide in page builders, theme options,
			// emails, etc.) — never auto-deleted, so no bulk actions here.
			if ( (int) $un['count'] < 1 ) {
				$this->render_empty_section_notice();
			} else {
				echo '<div class="notice notice-warning inline wpopt-notice"><p>' . wp_kses_post( __( '<strong>Heuristic — verify before deleting.</strong> These attachments have no detectable reference in featured images, post content, post meta (incl. galleries/ACF) or parent posts. But references can live in page builders, theme options, sliders, emails or external systems we can’t see. This list is <strong>read-only</strong>; confirm each is truly unused (e.g. in the Media Library) before removing it.', 'wpoptimizing' ) ) . '</p></div>';
				$dyn = $this->active_dynamic_media_sources();
				if ( ! empty( $dyn ) ) {
					echo '<div class="notice notice-warning inline wpopt-notice"><p>' . esc_html(
						sprintf(
							/* translators: %s: comma-separated plugin names. */
							__( 'Heads up: these active plugins often reference images dynamically, which this scan cannot see — %s. Be extra careful with images they might use.', 'wpoptimizing' ),
							implode( ', ', $dyn )
						)
					) . '</p></div>';
				}
				/*
				 * OTRO PLUGIN CON SU PROPIA LISTA DE «NO USADOS».
				 *
				 * No es trabajo duplicado —borrar un huérfano dos veces no hace nada— así que
				 * nuestra detección NO se retira: retirarla dejaría a quien mira con una sola
				 * lista y ningún aviso. El riesgo es que las dos listas se construyen con
				 * criterios distintos y las decide una persona con la que tenga en pantalla.
				 * Por eso el aviso va aquí, donde está el botón, y no en el panel de ajustes.
				 */
				$otros_medios = function_exists( 'wpoptimizing_compat_providers' )
					? wpoptimizing_compat_providers( 'media_cleanup' )
					: array();
				if ( ! empty( $otros_medios ) ) {
					echo '<div class="notice notice-warning inline wpopt-notice"><p>' . esc_html(
						sprintf(
							/* translators: %s: comma-separated plugin names. */
							__( 'These plugins keep their own list of unused media: %s. Each list is built with a different heuristic, so they will not agree — an item missing from one is not confirmation that the other is right. Check an item yourself before deleting it, whichever list you are looking at.', 'wpoptimizing' ),
							implode( ', ', array_map( 'strval', $otros_medios ) )
						)
					) . '</p></div>';
				}
				if ( $un_partial ) {
					// notice-WARNING, not notice-info. The rest of this detector is deliberately
					// biased towards "used", so a false positive is normally impossible — but a
					// bounded scan breaks exactly that bias: a reference past the row cap is not
					// weighed and discarded, it is never seen. On a store with tens of thousands
					// of distinct numeric meta values that is the ordinary case, not a corner one,
					// and the row above it says "Unused". Deletion is still backup-first and
					// restorable from the Backups tab, which is what the second sentence is for.
					echo '<div class="notice notice-warning inline wpopt-notice"><p>' . esc_html__( 'Detection was bounded on this large site, so some references may have been missed (more items may look unused than really are).', 'wpoptimizing' ) . ' ' . esc_html__( 'Media deletions are backed up first and can be restored from the Backups tab.', 'wpoptimizing' ) . '</p></div>';
				}
				$rows  = $this->filter_media_rows( (array) $un['sample'], 'file' );
				$table = new WPOptimizing_Unused_List_Table(
					$this,
					$rows,
					false,
					false,
					array(
						'scope'        => 'media',
						'per_page'     => $media_pp,
						'type_filter'  => $media_tipo,
						'type_choices' => $this->media_ext_choices( (array) $un['sample'], 'file' ),
						'baseurl'      => $baseurl,
						'can_delete'   => $can_delete,
					)
				);
				$table->prepare_items();
				$this->media_partial_notice( count( (array) $un['sample'] ), (int) $un['count'] );
				echo '<form method="get">';
				echo '<input type="hidden" name="page" value="wpoptimizing" />';
				echo '<input type="hidden" name="tab" value="media" />';
				echo '<input type="hidden" name="msec" value="unused" />';
				if ( $can_delete ) {
					$this->render_post_only_nonce();
				}
				$table->search_box( __( 'Search files', 'wpoptimizing' ), 'media' );
				$table->display();

				// "Mark as known" is always offered (non-destructive): it adds the
				// selected attachments to an allow-list so the heuristic stops flagging
				// the false positives the user has confirmed are in use (fonts a builder
				// loads, an image an SEO plugin references, etc.).
				$unused_ids = array();
				foreach ( (array) $un['sample'] as $u_row ) {
					$u_id = (int) ( $u_row['id'] ?? 0 );
					if ( $u_id > 0 ) {
						$unused_ids[] = $u_id;
					}
				}
				$trust_extra = array(
					'scope'            => 'trust_unused',
					'all_values'       => $unused_ids,
					'selected_label'   => __( 'Mark selected as known', 'wpoptimizing' ),
					'all_label'        => __( 'Mark all as known', 'wpoptimizing' ),
					'button_class'     => '',
					/* translators: %d: number of selected attachments. */
					'confirm_selected' => __( 'Mark the %d selected attachment(s) as known? They will stop appearing as unused.', 'wpoptimizing' ),
					/* translators: %d: number of attachments. */
					'confirm_all'      => __( 'Mark ALL %d attachment(s) as known? They will stop appearing as unused.', 'wpoptimizing' ),
				);
				if ( $can_delete ) {
					$this->render_bulk_controls(
						$table,
						array(
							'selected_label'   => __( 'Delete selected', 'wpoptimizing' ),
							'all_label'        => __( 'Delete all', 'wpoptimizing' ),
							'button_class'     => 'button-delete',
							'description'      => __( 'A backup is saved to the Backups tab before deletion, and a file that could not be fully backed up is never deleted. Or mark items as known to keep them and hide them from this list.', 'wpoptimizing' ),
							/* translators: %d: number of selected attachments. */
							'confirm_selected' => __( 'Delete the %d selected attachment(s)? A backup is created first.', 'wpoptimizing' ),
							/* translators: %d: number of filtered attachments. */
							'confirm_all'      => __( 'Delete ALL %d filtered attachment(s)? A backup is created first — and remember this list is heuristic, so verify they are truly unused.', 'wpoptimizing' ),
							// A bounded scan did not weigh every reference and discard it — it never
							// saw some of them. "Delete all" over a list built that way is the one
							// action that turns a detection limit into missing images, so it is
							// withdrawn and only an explicit, looked-at selection is accepted.
							'no_all'           => $un_partial,
							'extra_action'     => $trust_extra,
						)
					);
				} else {
					$this->render_bulk_controls(
						$table,
						array(
							'primary'      => false,
							'description'  => __( 'Marking as known keeps these files and hides them from the unused list (reset the known list any time). Deletion is a Pro feature.', 'wpoptimizing' ),
							'extra_action' => $trust_extra,
						)
					);
				}
				$this->render_trusted_attachments_note();
				echo '</form>';
			}
		} elseif ( 'duplicates' === $msec ) {
			// Duplicate images are Pro (23/10/2026): Lite shows the count the analysis found and the
			// note; Pro lists the sets and, with a license, cleans them.
			$dup_lite = true;
			if ( $dup_lite ) {
				$this->render_pro_note( __( 'Listing duplicate images and merging them (one copy kept, its references reassigned) is not included in this plugin.', 'wpoptimizing' ) );
			}
		} else {
			if ( 'thumbs' === $msec ) {
				$sample = (array) $ot['sample'];
				$total  = (int) $ot['count'];
			} elseif ( 'other' === $msec ) {
				$sample = (array) $oth['sample'];
				$total  = (int) $oth['count'];
			} else {
				$sample = (array) $of['sample'];
				$total  = (int) $of['count'];
			}

			if ( empty( $sample ) ) {
				$this->render_empty_section_notice();
			} else {
				$rows = $this->filter_media_rows( $sample, 'file' );

				// "Other files" live in named (plugin-like) folders, so offer a second
				// filter by suspected owner to make selective deletions easy. Reuses the
				// generic second-filter control (named "{scope}_ext" → media_ext).
				$owner_choices = array();
				$owner_filter  = '';
				if ( 'other' === $msec ) {
					foreach ( $sample as $orow ) {
						$own = $this->media_suspected_owner( (string) ( $orow['file'] ?? '' ) );
						if ( '' !== $own ) {
							$owner_choices[ $own ] = $own;
						}
					}
					ksort( $owner_choices );
					if ( isset( $_REQUEST['media_ext'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only list filter.
						$owner_filter = trim( sanitize_text_field( wp_unslash( $_REQUEST['media_ext'] ) ) ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended
						if ( '' === $owner_filter || 'all' === strtolower( $owner_filter ) || ! isset( $owner_choices[ $owner_filter ] ) ) {
							$owner_filter = '';
						}
					}
					if ( '' !== $owner_filter ) {
						$rows = array_values(
							array_filter(
								$rows,
								function ( $r ) use ( $owner_filter ) {
									return $this->media_suspected_owner( (string) ( $r['file'] ?? '' ) ) === $owner_filter;
								}
							)
						);
					}
				}

				$table = new WPOptimizing_Media_List_Table(
					$this,
					$rows,
					false,
					false,
					array(
						'scope'             => 'media',
						'per_page'          => $media_pp,
						'type_filter'       => $media_tipo,
						'type_choices'      => $this->media_ext_choices( $sample, 'file' ),
						'project_filter'    => $owner_filter,
						'project_choices'   => $owner_choices,
						'project_all_label' => __( 'All owners', 'wpoptimizing' ),
						'delete_prefix'     => $delete_prefix,
						'baseurl'           => $baseurl,
						'show_owner'        => ( 'other' === $msec ),
						'can_delete'        => $can_delete,
					)
				);
				$table->prepare_items();
				$this->media_partial_notice( count( $sample ), $total );

				echo '<form method="get">';
				echo '<input type="hidden" name="page" value="wpoptimizing" />';
				echo '<input type="hidden" name="tab" value="media" />';
				echo '<input type="hidden" name="msec" value="' . esc_attr( $msec ) . '" />';
				$this->render_post_only_nonce();
				$table->search_box( __( 'Search files', 'wpoptimizing' ), 'media' );
				$table->display();
				$this->render_bulk_controls(
					$table,
					array(
						'selected_label'   => __( 'Delete selected', 'wpoptimizing' ),
