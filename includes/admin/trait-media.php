	}

	/**
	 * Attach an attachment ID to each diagnostics row by resolving its uploads-relative path
	 * against _wp_attached_file in ONE query. Rows that do not map to an attachment get id=0.
	 *
	 * @param array $rows Rows with a 'rel' key.
	 * @return array Same rows with an added 'id'.
	 */
	protected function attach_media_ids( array $rows ) {
		global $wpdb;
		if ( empty( $rows ) || ! isset( $wpdb ) || ! is_object( $wpdb ) ) {
			return $rows;
		}
		$rels = array();
		foreach ( $rows as $r ) {
			$rel = (string) ( $r['rel'] ?? '' );
			if ( '' !== $rel ) {
				$rels[ $rel ] = true;
			}
		}
		$rels = array_keys( $rels );
		$map  = array();
		if ( ! empty( $rels ) ) {
			$ph = implode( ',', array_fill( 0, count( $rels ), '%s' ) );
			// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.PreparedSQLPlaceholders.UnfinishedPrepare
			$res = $wpdb->get_results( $wpdb->prepare( "SELECT post_id, meta_value FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND meta_value IN ($ph)", $rels ), ARRAY_A );
			foreach ( (array) $res as $row ) {
				$map[ (string) $row['meta_value'] ] = (int) $row['post_id'];
			}
		}
		foreach ( $rows as &$r ) {
			$rel     = (string) ( $r['rel'] ?? '' );
			$r['id'] = isset( $map[ $rel ] ) ? (int) $map[ $rel ] : 0;
		}
		unset( $r );
		return $rows;
	}

	/**
	 * "Heaviest images" subsection: the per-image diagnostics list table (thumbnail, dimensions,
	 * weight, capability-aware issue badges, estimated saving) with shared search/type-filter/
	 * pagination and, on Pro + a capable server, a bulk "Optimize selected" action that runs the
	 * async engine (run_bulk_batch 'image_opt'). Read-only otherwise.
	 *
	 * @return void
	 */
	protected function render_image_detective() {
		// Optimizar desde la lista es Pro: en Lite la lista es un diagnóstico y no promete botones que no tiene.
		$heavy_desc = __( 'The largest source images and what would help each one — oversized originals, missing WebP/AVIF copies and heavy files.', 'wpoptimizing' );
		$this->render_section_header(
			__( 'Heaviest images', 'wpoptimizing' ),
			$heavy_desc,
			array(
				'icon' => 'images-alt2',
				'doc'  => 'wpopt-doc-image',
			)
		);

		$s = function_exists( 'wpoptimizing_image_opt_cached' )
			? wpoptimizing_image_opt_cached()
			: ( function_exists( 'wpoptimizing_image_opt_scan' ) ? wpoptimizing_image_opt_scan( false ) : null );
		if ( ! is_array( $s ) || empty( $s['worst'] ) || ! is_array( $s['worst'] ) ) {
			$this->render_empty_section_notice( __( 'No heavy images found yet. Open “Image optimization” and run the analysis to populate this list.', 'wpoptimizing' ) );
			return;
		}

		// Optimizing is Pro: Lite keeps this diagnostic list and says so; the engine is not in it.
		$can_optimize = false;
		$webp_ok     = function_exists( 'wpoptimizing_image_webp_supported' ) && wpoptimizing_image_webp_supported();
		$avif_ok     = function_exists( 'wpoptimizing_image_avif_supported' ) && wpoptimizing_image_avif_supported();
		$comp_ok     = function_exists( 'wpoptimizing_image_compress_supported' ) && wpoptimizing_image_compress_supported();
		$actionable  = $can_optimize && ( $comp_ok || $webp_ok || $avif_ok );

		if ( ! $can_optimize ) {
			// Lite: qué no trae, sin candado; pro_hint() añade el enlace a Pro.
			$pro_banner = __( 'Bulk optimization of existing images (recompressing originals and generating their WebP/AVIF copies) is not included in this plugin.', 'wpoptimizing' );
			echo '<div class="notice notice-info inline wpopt-notice wpopt-pro-lock-banner"><p>'
				. esc_html( $pro_banner )
				. ' ' . $this->pro_hint() // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- pre-escaped badge.
				. '</p></div>';
		} elseif ( ! $comp_ok && ! $webp_ok && ! $avif_ok ) {
			echo '<div class="notice notice-warning inline wpopt-notice"><p>' . esc_html__( 'Your server cannot process images yet (it needs the GD or Imagick PHP extension), so these are shown for information only.', 'wpoptimizing' ) . '</p></div>';
		}

		$up      = wp_get_upload_dir();
		$baseurl = isset( $up['baseurl'] ) ? (string) $up['baseurl'] : '';

		// The shared media filter/type helpers key off a 'file' field; mirror 'rel' into it.
		$all_rows    = array();
		$total_bytes = 0;
		foreach ( (array) $s['worst'] as $r ) {
			if ( ! is_array( $r ) ) {
				continue;
			}
			$r['file']    = (string) ( $r['rel'] ?? '' );
			$total_bytes += (int) ( $r['bytes'] ?? 0 );
			$all_rows[]   = $r;
		}

		// Resolve each path to its attachment ID in ONE query (uploads-relative paths ARE the
		// _wp_attached_file values), so the list can link straight to the attachment editor.
		$all_rows = $this->attach_media_ids( $all_rows );

		// Two stat boxes, matching the other media subsections (Orphan files, Unused…).
		echo '<div class="wpopt-kpi-grid wpopt-section-totals">';
		printf(
			'<div class="wpopt-kpi"><div class="wpopt-kpi-num is-info">%1$s</div><div class="wpopt-kpi-label">%2$s</div></div>',
			esc_html( number_format_i18n( count( $all_rows ) ) ),
			esc_html__( 'Images to act on', 'wpoptimizing' )
		);
		printf(
			'<div class="wpopt-kpi"><div class="wpopt-kpi-num is-warn">%1$s</div><div class="wpopt-kpi-label">%2$s</div></div>',
			esc_html( size_format( $total_bytes, 1 ) ),
			esc_html__( 'Combined weight', 'wpoptimizing' )
		);
		echo '</div>';

		// Shared media lightbox (thumbnails open it, now with info + an edit link).
		$this->render_media_modal();

		$media_pp   = isset( $_GET['media_pp'] ) ? max( 25, (int) $_GET['media_pp'] ) : 50; // phpcs:ignore WordPress.Security.NonceVerification.Recommended
		$media_tipo = isset( $_GET['media_tipo'] ) ? sanitize_key( wp_unslash( $_GET['media_tipo'] ) ) : 'all'; // phpcs:ignore WordPress.Security.NonceVerification.Recommended

		$rows  = $this->filter_media_rows( $all_rows, 'file' );
		$table = new WPOptimizing_Image_Diag_List_Table(
			$this,
			$rows,
			false,
			false,
			array(
				'scope'        => 'media',
				'per_page'     => $media_pp,
				'type_filter'  => $media_tipo,
				'type_choices' => $this->media_ext_choices( $all_rows, 'file' ),
				'baseurl'      => $baseurl,
				'webp_ok'      => $webp_ok,
				'avif_ok'      => $avif_ok,
				'comp_ok'      => $comp_ok,
				'actionable'   => $actionable,
			)
		);
		$table->prepare_items();

		echo '<form method="get">';
		echo '<input type="hidden" name="page" value="wpoptimizing" />';
		echo '<input type="hidden" name="tab" value="media" />';
		echo '<input type="hidden" name="msec" value="heavy" />';
		if ( $actionable ) {
			$this->render_post_only_nonce();
		}
		$table->search_box( __( 'Search images', 'wpoptimizing' ), 'media' );
		$table->display();
		echo '</form>';
	}

	/**
	 * Add, remove or check the WebP/AVIF rule of the uploads .htaccess (self-POST). Dies on a
	 * bad nonce; prints its own notice.
	 *
	 * @return void
	 */
	protected function maybe_nextgen_rewrite_action() {
		// phpcs:ignore WordPress.Security.NonceVerification.Missing -- verified by check_admin_referer() below before anything is acted on.
		$do = isset( $_POST['wpopt_img_rewrite'] ) ? sanitize_key( wp_unslash( $_POST['wpopt_img_rewrite'] ) ) : '';
		if ( '' === $do || ! function_exists( 'wpoptimizing_nextgen_rewrite_apply' ) ) {
			return;
		}
		check_admin_referer( 'wpopt_img_rewrite' );
		if ( ! current_user_can( wpoptimizing_cap() ) ) {
			return;
		}
		if ( 'check' !== $do ) {
			$r = wpoptimizing_nextgen_rewrite_apply( 'on' === $do );
			if ( empty( $r['ok'] ) ) {
				if ( 'foreign' === $r['code'] ) {
					/* translators: %s: plugin name. */
					$msg = sprintf( __( '%s already serves WebP/AVIF, so the rule was not added.', 'wpoptimizing' ), (string) $r['owner'] );
				} elseif ( 'nobackup' === $r['code'] ) {
					$msg = wpoptimizing_backup_failure_message( wpoptimizing_backup_failure() );
				} else {
					$msg = __( 'The .htaccess file in the uploads folder could not be written. Nothing was changed.', 'wpoptimizing' );
				}
				echo '<div class="notice notice-error inline wpopt-notice"><p>' . esc_html( $msg ) . '</p></div>';
				return;
			}
			if ( 'on' !== $do ) {
				echo '<div class="notice notice-success inline wpopt-notice"><p>' . esc_html__( 'The WebP/AVIF rule was removed from the uploads folder.', 'wpoptimizing' ) . '</p></div>';
				return;
			}
		}
		// Adding it checks it straight away: the rule is only worth having if the server obeys it.
		$c  = wpoptimizing_nextgen_rewrite_check();
		$ok = 'works' === $c['state'];
		echo '<div class="notice ' . ( $ok ? 'notice-success' : 'notice-warning' ) . ' inline wpopt-notice"><p>' . esc_html( $this->nextgen_rewrite_check_text( $c ) ) . '</p></div>';
	}

	/**
	 * One sentence for a check result.
	 *
	 * @param array $c Result of wpoptimizing_nextgen_rewrite_check().
	 * @return string
	 */
	protected function nextgen_rewrite_check_text( array $c ) {
		switch ( $c['state'] ) {
			case 'works':
				/* translators: %s: image format, AVIF or WebP. */
				return sprintf( __( 'Works: asked for a JPEG/PNG the way a browser does, the server answered with its %s copy.', 'wpoptimizing' ), strtoupper( (string) ( $c['got'] ?? '' ) ) );
			case 'not_applied':
				return __( 'The server still answers with the original image. mod_rewrite may be off, or another rule answers first: ask your host, or use the <picture> serving.', 'wpoptimizing' );
			case 'error':
				return __( 'The test image could not be requested from the server, so nothing could be checked.', 'wpoptimizing' );
			default:
				// En Lite no hay botón para generar las copias de la biblioteca existente.
				$no_copy = __( 'No image has a WebP or AVIF copy yet, so there is nothing to check.', 'wpoptimizing' );
				return $no_copy;
		}
	}

	/**
	 * The "Serve WebP/AVIF from the server" box: state, buttons, last check and its warnings,
	 * or the Nginx configuration.
	 *
	 * @return void
	 */
	protected function render_nextgen_rewrite() {
		if ( ! function_exists( 'wpoptimizing_nextgen_rewrite_active' ) ) {
			return;
		}
		echo '<div class="wpopt-audit-protect">';
		echo '<h3 class="wpopt-img-group-title">' . esc_html__( 'Serve WebP/AVIF from the server', 'wpoptimizing' ) . '</h3>';
		echo '<p class="description">' . esc_html__( 'A rule in the uploads folder answers each request for a JPEG, PNG or GIF with its AVIF or WebP copy when the browser accepts it. The address does not change, so it also covers backgrounds in CSS files, page builders and images the theme prints, without any PHP. Images without a copy are served as always.', 'wpoptimizing' ) . '</p>';
		if ( function_exists( 'wpoptimizing_media_audit_is_nginx' ) && wpoptimizing_media_audit_is_nginx() ) {
			$up   = wp_get_upload_dir();
			$path = (string) wp_parse_url( (string) ( $up['baseurl'] ?? '' ), PHP_URL_PATH );
			echo '<p>' . esc_html__( 'This server runs Nginx, which does not read .htaccess. Add this to its configuration, or ask your host to:', 'wpoptimizing' ) . '</p>';
			echo '<pre class="wpopt-audit-snippet"><code>' . esc_html( wpoptimizing_nextgen_rewrite_nginx_snippet( '' !== $path ? $path : '/wp-content/uploads' ) ) . '</code></pre></div>';
			return;
		}
		$on    = wpoptimizing_nextgen_rewrite_active();
		$owner = function_exists( 'wpoptimizing_image_nextgen_serving_conflict' ) ? wpoptimizing_image_nextgen_serving_conflict() : '';
		if ( ! $on && '' !== $owner ) {
			/* translators: %s: plugin name. */
			echo '<p>' . esc_html( sprintf( __( '%s already serves WebP/AVIF on this site, so this stays off.', 'wpoptimizing' ), $owner ) ) . '</p></div>';
			return;
		}
		echo '<form method="post">';
		wp_nonce_field( 'wpopt_img_rewrite' );
		echo '<p>';
		if ( $on ) {
			echo '<span class="wpopt-badge-crowd">' . esc_html__( 'Active', 'wpoptimizing' ) . '</span> ';
			echo '<button type="submit" name="wpopt_img_rewrite" value="check" class="button">' . esc_html__( 'Check now', 'wpoptimizing' ) . '</button> ';
			echo '<button type="submit" name="wpopt_img_rewrite" value="off" class="button">' . esc_html__( 'Remove the rule', 'wpoptimizing' ) . '</button>';
		} else {
			echo '<button type="submit" name="wpopt_img_rewrite" value="on" class="button">' . esc_html__( 'Add the rule and check it', 'wpoptimizing' ) . '</button>';
		}
		echo '</p></form>';
		$c = $on ? wpoptimizing_nextgen_rewrite_last_check() : null;
		if ( $c ) {
			echo '<p class="description">' . esc_html( $this->nextgen_rewrite_check_text( $c ) ) . '</p>';
			if ( 'works' === $c['state'] && empty( $c['vary'] ) ) {
				echo '<p class="description">' . esc_html__( 'The answer carries no "Vary: Accept" header (mod_headers may be off): a shared cache could hand an AVIF to a browser that cannot show it. Ask your host to enable mod_headers.', 'wpoptimizing' ) . '</p>';
			}
			if ( ! empty( $c['cdn'] ) ) {
				/* translators: %s: CDN or cache name(s). */
				echo '<p class="description">' . esc_html( sprintf( __( 'The images pass through %s. It has to keep one copy per format (Vary: Accept); if your plan does not, remove the rule and keep the <picture> serving, which works behind any CDN.', 'wpoptimizing' ), (string) $c['cdn'] ) ) . '</p>';
			}
		}
		echo '</div>';
	}


	protected function render_image_optimization() {
		// Lite sólo reduce lo que se sube (recompresión y WebP al subir son Pro): la descripción cuenta sólo eso.
		$imgopt_desc = __( 'Analyze the images in your uploads — total weight, formats, large files and how many lack a WebP/AVIF copy. Oversized new uploads are scaled down as they arrive, and serving the next-gen copies on the front-end is built in.', 'wpoptimizing' );
		$this->render_section_header(
			__( 'Image optimization', 'wpoptimizing' ),
			$imgopt_desc,
			array(
				'icon' => 'format-image',
				'doc'  => 'wpopt-doc-image',
			)
		);
		if ( ! function_exists( 'wpoptimizing_image_opt_scan' ) ) {
			return;
		}

		// Save the image settings form (self-POST). Dies on a bad nonce.
		if ( isset( $_POST['wpopt_img_settings'] ) ) {
			check_admin_referer( 'wpopt_img_settings' );
			if ( current_user_can( wpoptimizing_cap() ) ) {
				$page_pass_before = ! empty( wpoptimizing_image_settings()['serve_nextgen_page'] );
				$q                = isset( $_POST['wpopt_img_quality'] ) ? absint( wp_unslash( $_POST['wpopt_img_quality'] ) ) : 82;
				$mw               = isset( $_POST['wpopt_img_max_width'] ) ? absint( wp_unslash( $_POST['wpopt_img_max_width'] ) ) : 2560;
				$mh               = isset( $_POST['wpopt_img_max_height'] ) ? absint( wp_unslash( $_POST['wpopt_img_max_height'] ) ) : 2560;
				update_option(
					'wpoptimizing_image_settings',
					array(
						'quality'            => max( 40, min( 100, $q ) ),
						'max_width'          => max( 0, min( 20000, $mw ) ),
						'max_height'         => max( 0, min( 20000, $mh ) ),
						'lossless'           => isset( $_POST['wpopt_img_lossless'] ) ? 1 : 0,
						'strip_meta'         => isset( $_POST['wpopt_img_strip_meta'] ) ? 1 : 0,
						'resize_uploads'     => isset( $_POST['wpopt_img_resize_uploads'] ) ? 1 : 0,
						'serve_nextgen'      => isset( $_POST['wpopt_img_serve_nextgen'] ) ? 1 : 0,
						'serve_nextgen_page' => isset( $_POST['wpopt_img_serve_nextgen_page'] ) ? 1 : 0,
						'webp_quality'       => isset( $_POST['wpopt_img_webp_quality'] ) ? absint( wp_unslash( $_POST['wpopt_img_webp_quality'] ) ) : 0,
						'avif_quality'       => isset( $_POST['wpopt_img_avif_quality'] ) ? absint( wp_unslash( $_POST['wpopt_img_avif_quality'] ) ) : 0,
						'exclude'            => wpoptimizing_image_exclude_normalize( isset( $_POST['wpopt_img_exclude'] ) ? sanitize_textarea_field( wp_unslash( $_POST['wpopt_img_exclude'] ) ) : '' ), // phpcs:ignore WordPressVIPMinimum.Performance.WPQueryParams.PostNotIn_exclude -- Our image exclusion list, not a query argument.
						'disabled_sizes'     => wpoptimizing_image_disabled_sizes_normalize( isset( $_POST['wpopt_img_disabled_sizes'] ) ? array_map( 'sanitize_key', (array) wp_unslash( $_POST['wpopt_img_disabled_sizes'] ) ) : array() ),
					),
					true
				);
				// Pages already cached were stored without (or with) the page pass: start over.
				if ( isset( $_POST['wpopt_img_serve_nextgen_page'] ) !== $page_pass_before && function_exists( 'wpoptimizing_page_cache_clear' ) ) {
					wpoptimizing_page_cache_clear();
				}
				echo '<div class="notice notice-success inline wpopt-notice"><p>' . esc_html__( 'Image settings saved.', 'wpoptimizing' ) . '</p></div>';
			}
		}
		$this->maybe_nextgen_rewrite_action();

		$force = false;
		if ( isset( $_GET['wpopt_img_rescan'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- nonce checked next.
			$nonce = isset( $_GET['_wpopt_img'] ) ? sanitize_text_field( wp_unslash( $_GET['_wpopt_img'] ) ) : '';
			if ( wp_verify_nonce( $nonce, 'wpopt_img_rescan' ) && current_user_can( wpoptimizing_cap() ) ) {
				$force = true;
			}
