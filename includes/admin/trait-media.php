	/**
	 * Backup entries ("media::<wp-content-relative>") for every file deleting an attachment
	 * removes: its uploads files (WPOPT_Media_Deduper::files_from_meta()) and the pre-compression
	 * original this plugin keeps in image-originals/, which its wp_delete_file filter deletes
	 * along with the image. Empty when the uploads folder is outside wp-content, where the
	 * file backup cannot reach — the caller must then not delete.
	 *
	 * @param int $id Attachment ID.
	 * @return string[]
	 */
	protected function attachment_backup_entries( $id ) {
		if ( ! class_exists( 'WPOPT_Media_Deduper' ) ) {
			return array();
		}
		$uploads      = wp_get_upload_dir();
		$content_base = wp_normalize_path( trailingslashit( WP_CONTENT_DIR ) );
		$uploads_base = ! empty( $uploads['basedir'] ) ? wp_normalize_path( trailingslashit( (string) $uploads['basedir'] ) ) : '';
		if ( '' === $uploads_base || 0 !== strpos( $uploads_base, $content_base ) ) {
			return array();
		}
		$prefix = ltrim( substr( $uploads_base, strlen( $content_base ) ), '/' );
		$orig   = function_exists( 'wpoptimizing_image_compress_backup_dir' ) ? wpoptimizing_image_compress_backup_dir() : trailingslashit( WPOPT_DIR ) . 'image-originals/';
		$orig   = wp_normalize_path( (string) $orig );
		$orig   = ( '' !== $orig && 0 === strpos( $orig, $content_base ) ) ? trailingslashit( substr( $orig, strlen( $content_base ) ) ) : '';

		$out = array();
		foreach ( WPOPT_Media_Deduper::attachment_files_relative( $id ) as $rel ) {
			$out[] = 'media::' . $prefix . $rel;
			if ( '' !== $orig ) {
				$out[] = 'media::' . $orig . $rel;
			}
		}
		return array_values( array_unique( $out ) );
	}

	/**
	 * Save the database side of attachments into the current operation's backup, before
	 * wp_delete_attachment() removes it: the post row, all its postmeta, its term
	 * relationships (one cpt_post record each, the format restore_db_backup() already
	 * rebuilds), and every other post's _thumbnail_id pointing at it (post_meta records,
	 * restored the same way). Until now an "undo" brought the files back to a library that no
	 * longer had them, and the pages that used them as featured image stayed without one.
	 *
	 * @param int[]  $ids     Attachment IDs.
	 * @param string $trigger Backup reason.
	 * @return bool Whether every record was written.
	 */
	protected function backup_attachment_rows( array $ids, $trigger ) {
		global $wpdb;
		if ( empty( $ids ) || ! $this->ensure_backup_dir() ) {
			return false;
		}
		$path    = $this->backup_db_file_path( 'post' );
		$now     = time();
		$records = array();
		foreach ( $ids as $id ) {
			$id = (int) $id;
			// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
			$post = $wpdb->get_row( $wpdb->prepare( "SELECT * FROM {$wpdb->posts} WHERE ID = %d", $id ), ARRAY_A );
			if ( empty( $post ) ) {
				return false;
			}
			$records[] = array(
				'ts'   => $now,
				'type' => 'cpt_post',
				'post' => $post,
				'meta' => $wpdb->get_results( $wpdb->prepare( "SELECT * FROM {$wpdb->postmeta} WHERE post_id = %d", $id ), ARRAY_A ),
				'rels' => $wpdb->get_results( $wpdb->prepare( "SELECT * FROM {$wpdb->term_relationships} WHERE object_id = %d", $id ), ARRAY_A ),
			);
			$thumbs    = $wpdb->get_results( $wpdb->prepare( "SELECT * FROM {$wpdb->postmeta} WHERE meta_key = '_thumbnail_id' AND meta_value = %s", (string) $id ), ARRAY_A );
			// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
			if ( '' !== (string) $wpdb->last_error ) {
				return false;
			}
			foreach ( (array) $thumbs as $row ) {
				$records[] = array(
					'ts'   => $now,
					'type' => 'post_meta',
					'row'  => $row,
				);
			}
		}
		clearstatcache( true, $path );
		$before = is_file( $path ) ? (int) filesize( $path ) : 0;
		$bytes  = 0;
		foreach ( $records as $rec ) {
			$line = wp_json_encode( $rec );
			if ( false === $line ) {
				return false;
			}
			$bytes += strlen( $line ) + 1;
			$this->append_jsonl( $path, $rec );
		}
		clearstatcache( true, $path );
		if ( ( is_file( $path ) ? (int) filesize( $path ) : 0 ) < $before + $bytes ) {
			return false;
		}
		$labels = array();
		foreach ( $ids as $id ) {
			$labels[] = 'post::attachment #' . (int) $id;
		}
		$this->record_backup_manifest( $this->backup_op_key, $trigger, $labels );
		return true;
	}

	/**
	 * @param int[] $ids Attachment ids.
	 * @return array{deleted:int,skipped:int,backed:int}
	 */
	protected function delete_unused_batch( array $ids ) {
		global $wpdb;
		$ids = array_values( array_unique( array_filter( array_map( 'absint', $ids ) ) ) );
		if ( empty( $ids ) ) {
			return array(
				'deleted' => 0,
				'skipped' => 0,
				'backed'  => 0,
			);
		}

		$deleted = 0;
		$skipped = 0;
		$backed  = 0;

		// The list being acted on is a report, possibly days old. Ask the database again,
		// for these IDs, whether anything points at them now; if it cannot answer in time,
		// delete nothing in this batch.
		$atts = array();
		foreach ( $ids as $id ) {
			if ( 'attachment' === get_post_type( $id ) ) {
				$atts[ $id ] = (string) get_post_meta( $id, '_wp_attached_file', true );
			}
		}
		$in_use = ( ! empty( $atts ) && class_exists( 'WPOPT_Media_Analyzer' ) ) ? ( new WPOPT_Media_Analyzer() )->referenced_now( $atts ) : array();

		foreach ( $ids as $id ) {
			if ( ! isset( $atts[ $id ] ) || null === $in_use || isset( $in_use[ $id ] ) ) {
				++$skipped;
				continue;
			}
			// Never force-delete a file another attachment still points to (it would
			// break the survivor); skip such an attachment.
			$att_file = $atts[ $id ];
			if ( '' !== $att_file ) {
				$shared = (int) $wpdb->get_var( // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching
					$wpdb->prepare(
						"SELECT COUNT(*) FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND meta_value = %s AND post_id <> %d",
						$att_file,
						$id
					)
				);
				if ( $shared > 0 ) {
					++$skipped;
					continue;
				}
			}
			// Backup-first is MANDATORY: if the files cannot be resolved/copied (e.g. the
			// uploads dir is outside wp-content), SKIP — never delete without a verified
			// copy. (Was: an empty path list silently skipped the backup and deleted.)
			$backup_paths = $this->attachment_backup_entries( $id );
			if ( empty( $backup_paths ) ) {
				++$skipped;
				continue;
			}
			$bk = $this->backup_fs_paths( $backup_paths, 'unused' );
			if ( empty( $bk['ok'] ) || (int) $bk['copied'] < 1 || (int) $bk['copied'] < (int) $bk['attempted'] ) {
				++$skipped;
				continue;
			}
			$backed += (int) $bk['copied'];
			// And the record itself, or the restore brings back files nothing lists.
			if ( ! $this->backup_attachment_rows( array( $id ), 'unused' ) ) {
				++$skipped;
				continue;
			}
			if ( wp_delete_attachment( $id, true ) ) {
				++$deleted;
			} else {
				++$skipped;
			}
		}

		// Prune the cached media report in place (counts drop, rows disappear).
		$report = wpoptimizing_media_report_get();
		if ( is_array( $report ) && isset( $report['unused']['sample'] ) ) {
			$del                        = array_flip( $ids );
			$report['unused']['sample'] = array_values(
				array_filter(
					(array) $report['unused']['sample'],
					static function ( $r ) use ( $del ) {
						return ! isset( $del[ (int) ( $r['id'] ?? 0 ) ] );
					}
				)
			);
			$report['unused']['count']  = max( 0, (int) ( $report['unused']['count'] ?? 0 ) - $deleted );
			wpoptimizing_media_report_save( $report );
			if ( function_exists( 'wpoptimizing_store_media_stats' ) ) {
				wpoptimizing_store_media_stats( $report );
			}
		}

		if ( function_exists( 'wpoptimizing_audit_log' ) ) {
			wpoptimizing_audit_log(
				'media_unused_delete',
				array(
					'deleted'   => $deleted,
					'skipped'   => $skipped,
					'backed_up' => $backed,
				)
			);
		}

		return array(
			'deleted' => $deleted,
			'skipped' => $skipped,
			'backed'  => $backed,
		);
	}

