	/**
	 * Best-effort guess of which plugin/source a non-media upload file belongs to,
	 * from its top-level folder name.
	 *
	 * @param string $rel Path relative to uploads.
	 * @return string Owner label, or '' if none.
	 */
	public function media_suspected_owner( $rel ) {
		$top = strtolower( (string) strtok( (string) $rel, '/' ) );
		if ( '' === $top ) {
			return '';
		}

		/**
		 * Optional manual overrides (folder name => owner label). Empty by default;
		 * attribution otherwise comes from the plugin's filesystem knowledge base.
		 *
		 * @since 0.1.0
		 * @param array $overrides folder name (lower-case) => owner label.
		 */
		$overrides = (array) apply_filters( 'wpoptimizing_media_dir_owners', array() );
		if ( isset( $overrides[ $top ] ) ) {
			return (string) $overrides[ $top ];
		}

		// Knowledge base: the FS scan attributes uploads folders (runtime map +
		// dataset). Resolve the attributed slug to the installed plugin/theme name.
		$slug = $this->media_owner_map()[ $top ] ?? '';
		if ( '' !== $slug ) {
			$plugins = $this->get_all_plugins_by_slug();
			if ( isset( $plugins[ $slug ] ) ) {
				return (string) $plugins[ $slug ];
			}
			$themes = $this->get_all_themes_by_slug();
			if ( isset( $themes[ $slug ] ) ) {
				return (string) $themes[ $slug ];
			}
			// Not installed: the wordpress.org name, like every other table, or the slug.
			return $this->ext_display_name( $slug );
		}

		// Fallback: match the folder against installed plugins/themes by their
		// main-file basename or slug segments (uploads/apg-city ← wc-apg-city,
		// uploads/woocommerce_uploads ← woocommerce). Real install data, no map.
		$installed = $this->media_owner_from_installed( $top );
		if ( '' !== $installed ) {
			return $installed;
		}

		/* translators: %s: folder name. */
		return sprintf( __( '%s (unknown)', 'wpoptimizing' ), $top );
	}

	/**
	 * Best-effort owner of an unattributed uploads folder, matched against the
	 * currently installed plugins/themes. Two signals, strongest first:
	 *  1. A plugin whose main-file basename equals the folder
	 *     (uploads/apg-city ← wc-apg-city/apg-city.php).
	 *  2. The folder and an installed slug share a hyphen/underscore-delimited
	 *     segment (apg-city ⊂ wc-apg-city; woocommerce ⊂ woocommerce_uploads).
	 * Cached per request per folder.
	 *
	 * @param string $folder Lower-case top-level uploads folder name.
	 * @return string Plugin/theme name, or '' if no confident match.
	 */
	protected function media_owner_from_installed( $folder ) {
		static $cache = array();
		$folder       = strtolower( trim( (string) $folder ) );
		if ( strlen( $folder ) < 4 ) {
			return '';
		}
		if ( isset( $cache[ $folder ] ) ) {
			return $cache[ $folder ];
		}

		require_once ABSPATH . 'wp-admin/includes/plugin.php';
		$plugins = function_exists( 'get_plugins' ) ? get_plugins() : array();

		// 1) Main-file basename match (very specific, no false positives).
		foreach ( $plugins as $file => $data ) {
			if ( strtolower( basename( (string) $file, '.php' ) ) === $folder ) {
				return $cache[ $folder ] = (string) ( $data['Name'] ?? $folder );
			}
		}

		// 2) Slug-segment relationship against plugins, then themes.
		foreach ( array( $this->get_all_plugins_by_slug(), $this->get_all_themes_by_slug() ) as $map ) {
			foreach ( $map as $slug => $name ) {
				if ( $this->slug_segment_related( $folder, strtolower( (string) $slug ) ) ) {
					return $cache[ $folder ] = (string) $name;
				}
			}
		}

		return $cache[ $folder ] = '';
	}

	/**
	 * Whether two slugs are related as whole hyphen/underscore-delimited segments
	 * (so "apg-city" matches "wc-apg-city" but "city" would not match "ferocity").
	 *
	 * @param string $a First slug.
	 * @param string $b Second slug.
	 * @return bool
	 */
	protected function slug_segment_related( $a, $b ) {
		if ( $a === $b ) {
			return true;
		}
		foreach ( array( array( $a, $b ), array( $b, $a ) ) as $pair ) {
			list( $hay, $need ) = $pair;
			if ( strlen( $need ) < 4 ) {
				continue;
			}
			$pos = strpos( $hay, $need );
			while ( false !== $pos ) {
				$before  = ( 0 === $pos ) ? '' : $hay[ $pos - 1 ];
				$end_pos = $pos + strlen( $need );
				$after   = ( $end_pos >= strlen( $hay ) ) ? '' : $hay[ $end_pos ];
				$b_ok    = ( '' === $before || '-' === $before || '_' === $before );
				$a_ok    = ( '' === $after || '-' === $after || '_' === $after );
				if ( $b_ok && $a_ok ) {
					return true;
				}
				$pos = strpos( $hay, $need, $pos + 1 );
			}
		}
		return false;
	}

	/**
	 * Map of top-level uploads folder => attributed slug, read from the last
	 * filesystem scan (the plugin's attribution knowledge base). Cached.
	 *
	 * @return array<string,string>
	 */
	protected function media_owner_map() {
		static $cache = null;
		if ( null !== $cache ) {
			return $cache;
		}
		$cache = array();
		$path  = defined( 'WPOPT_CSV_SCAN_FS' ) ? WPOPT_CSV_SCAN_FS : '';
		if ( '' === $path || ! is_readable( $path ) ) {
			return $cache;
		}
		// Scan CSVs are encrypted at rest; read through the transparent handle
		// (no-op on plaintext) so the owner map is not parsed from ciphertext.
		$fh = function_exists( 'wpoptimizing_scan_read_handle' ) ? wpoptimizing_scan_read_handle( $path ) : fopen( $path, 'r' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fopen -- decrypts at-rest CSVs transparently.
		if ( ! $fh ) {
			return $cache;
		}
		$first = fgets( $fh );
		if ( false === $first ) {
			fclose( $fh ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose
			return $cache;
		}
		$delims = array(
			','  => substr_count( $first, ',' ),
			"\t" => substr_count( $first, "\t" ),
			';'  => substr_count( $first, ';' ),
		);
		arsort( $delims );
		$delim  = (string) array_key_first( $delims );
		$header = array_flip( array_map( 'strtolower', array_map( 'trim', (array) str_getcsv( $first, $delim, '"', '\\' ) ) ) );
		$pi     = $header['relative_path'] ?? $header['ruta_relativa'] ?? null;
		$si     = $header['project_slugs'] ?? $header['proyecto_slugs'] ?? null;
		if ( null === $pi || null === $si ) {
			fclose( $fh ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose
			return $cache;
		}
		while ( ( $r = fgetcsv( $fh, 0, $delim, '"', '\\' ) ) !== false ) {
			$rel = isset( $r[ $pi ] ) ? strtolower( str_replace( '\\', '/', trim( (string) $r[ $pi ] ) ) ) : '';
			if ( 0 !== strpos( $rel, 'uploads/' ) ) {
				continue;
			}
			$sub = substr( $rel, strlen( 'uploads/' ) );
			if ( false === strpos( $sub, '/' ) ) {
				continue; // A file in the uploads root, not a named folder.
			}
			$folder = (string) strtok( $sub, '/' );
			if ( '' === $folder || isset( $cache[ $folder ] ) ) {
				continue;
			}
			$slugs = isset( $r[ $si ] ) ? (string) $r[ $si ] : '';
			$slug  = '' !== $slugs ? trim( (string) strtok( $slugs, '|' ) ) : '';
			if ( '' !== $slug ) {
				$cache[ $folder ] = $slug;
			}
		}
		fclose( $fh ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose
		return $cache;
	}

