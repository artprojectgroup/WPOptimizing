					/* translators: %s: number of file-backup sets. */
					__( 'Deleted media is recoverable — file backups available: %s.', 'wpoptimizing' ),
					number_format_i18n( $fs_groups )
				)
			)
			. ' <a href="' . esc_url( $url ) . '">' . esc_html__( 'Restore from Backups', 'wpoptimizing' ) . '</a></p></div>';
