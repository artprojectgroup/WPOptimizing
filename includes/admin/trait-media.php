	/**
	 * Fast candidate count for the subsection nav badge: attachments whose metadata
	 * mentions a leftover marker. Cheap SQL COUNT (no per-file checks); may slightly
	 * overcount if a backup was already removed, which is fine for a badge.
	 *
	 * @return int
	 */
	protected function rename_leftover_count() {
		global $wpdb;
		if ( ! isset( $wpdb ) || ! is_object( $wpdb ) ) {
			return 0;
		}
		$markers = (array) apply_filters( 'wpoptimizing_rename_leftover_markers', array( '-mfrh-original' ) );
		$likes   = array();
		$params  = array();
		foreach ( $markers as $mk ) {
			$mk = (string) $mk;
			if ( '' !== $mk ) {
				$likes[]  = 'meta_value LIKE %s';
				$params[] = '%' . $wpdb->esc_like( $mk ) . '%';
			}
		}
		if ( empty( $likes ) ) {
			return 0;
		}
		// $where is built ONLY from the fixed literal clause 'meta_value LIKE %s' (one per
		// marker); no user data is interpolated — every value is a bound %s placeholder.
		$where = implode( ' OR ', $likes );
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.PreparedSQLPlaceholders.UnfinishedPrepare, PluginCheck.Security.DirectDB.UnescapedDBParameter
		return (int) $wpdb->get_var( $wpdb->prepare( "SELECT COUNT(*) FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attachment_metadata' AND ( {$where} )", $params ) );
	}

	/**
	 * Rows for the "Renamed-original backups" subsection: rename-plugin leftovers
	 * (e.g. Media File Renamer's *-mfrh-original.*) that are registered as an
	 * attachment's original_image and still exist on disk. The renamed file is
	 * already served, so these are redundant backups.
	 *
	 * @return array<int,array{file:string,id:int,type:string,size_bytes:int,served:string}>
	 */
	protected function rename_leftover_rows() {
		global $wpdb;
		if ( ! isset( $wpdb ) || ! is_object( $wpdb ) || ! class_exists( 'WPOPT_Media_Analyzer' ) ) {
			return array();
		}
		$up      = wp_get_upload_dir();
		$basedir = ! empty( $up['basedir'] ) ? wp_normalize_path( trailingslashit( (string) $up['basedir'] ) ) : '';
		if ( '' === $basedir ) {
			return array();
		}
		// Narrow to attachments whose metadata mentions a known leftover marker, then
		// confirm precisely in PHP (respecting the filterable marker list).
		$markers = (array) apply_filters( 'wpoptimizing_rename_leftover_markers', array( '-mfrh-original' ) );
		$likes   = array();
		$params  = array();
		foreach ( $markers as $mk ) {
			$mk = (string) $mk;
			if ( '' !== $mk ) {
				$likes[]  = 'm.meta_value LIKE %s';
				$params[] = '%' . $wpdb->esc_like( $mk ) . '%';
			}
		}
		if ( empty( $likes ) ) {
			return array();
		}
		// $where is built ONLY from the fixed literal clause 'm.meta_value LIKE %s' (one per
		// marker); no user data is interpolated — every value is a bound %s placeholder.
		$where = implode( ' OR ', $likes );
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.PreparedSQLPlaceholders.UnfinishedPrepare, PluginCheck.Security.DirectDB.UnescapedDBParameter
		$res  = $wpdb->get_results( $wpdb->prepare( "SELECT m.post_id AS id, f.meta_value AS attached, m.meta_value AS meta FROM {$wpdb->postmeta} m INNER JOIN {$wpdb->postmeta} f ON f.post_id = m.post_id AND f.meta_key = '_wp_attachment_metadata' WHERE m.meta_key = '_wp_attachment_metadata' AND ( {$where} )", $params ), ARRAY_A );
		$rows = array();
		foreach ( (array) $res as $r ) {
			$meta = maybe_unserialize( (string) $r['meta'] );
			if ( ! is_array( $meta ) || empty( $meta['original_image'] ) ) {
				continue;
			}
			$orig = (string) $meta['original_image'];
			if ( ! WPOPT_Media_Analyzer::is_rename_leftover( $orig ) ) {
				continue;
			}
			$attached = ltrim( (string) $r['attached'], '/' );
			$dir      = ( false !== strpos( $attached, '/' ) ) ? substr( $attached, 0, strrpos( $attached, '/' ) ) : '';
			$rel      = ( '' !== $dir ? $dir . '/' : '' ) . $orig;
			$abs      = $basedir . $rel;
			if ( ! is_file( $abs ) ) {
				continue; // Backup already gone.
			}
			$rows[] = array(
				'file'       => $rel,
				'id'         => (int) $r['id'],
				'type'       => strtolower( (string) pathinfo( $rel, PATHINFO_EXTENSION ) ),
				'size_bytes' => (int) filesize( $abs ),
				'served'     => $attached,
			);
		}
		return $rows;
	}

