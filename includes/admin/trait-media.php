	/**
	 * How many published posts carry each size's class (size-NAME, which the editor adds to an
	 * image placed at that size). Cached for a day: one LIKE per size over the posts table.
	 *
	 * @param string[] $names Size names.
	 * @return array<string,int>
	 */
	protected function image_sizes_content_usage( array $names ) {
		$key    = 'wpoptimizing_img_size_usage_' . md5( implode( ',', $names ) );
		$cached = get_transient( $key );
		if ( is_array( $cached ) ) {
			return $cached;
		}
		global $wpdb;
		$out = array();
		foreach ( $names as $name ) {
			$out[ $name ] = (int) $wpdb->get_var( $wpdb->prepare( "SELECT COUNT(*) FROM {$wpdb->posts} WHERE post_status = %s AND post_type NOT IN ( 'revision', 'attachment' ) AND post_content LIKE %s", 'publish', '%' . $wpdb->esc_like( 'size-' . $name ) . '%' ) ); // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching -- cached in a transient right below.
		}
		set_transient( $key, $out, DAY_IN_SECONDS );
		return $out;
	}

