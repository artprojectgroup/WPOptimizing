		$exts = array();
		foreach ( $rows as $r ) {
			$e = strtolower( pathinfo( $this->media_row_file( $r, $kind ), PATHINFO_EXTENSION ) );
			if ( '' !== $e ) {
				$exts[ $e ] = true;
			}
		}
		$exts = array_keys( $exts );
		sort( $exts );
		return $exts;
	}

	/**
	 * Filter a media sample by the search box ('s') and the extension dropdown
	 * ('media_tipo'). The list table itself only sorts + paginates, so search and
	 * type filtering happen here (mirrors how the Autoload/FS tabs pre-filter).
	 *
	 * @param array  $rows Sample rows.
	 * @param string $kind 'dup' or 'file'.
	 * @return array Filtered rows (re-indexed).
	 */
	protected function filter_media_rows( array $rows, $kind ) {
		// phpcs:disable WordPress.Security.NonceVerification.Recommended -- Read-only GET filters.
		$search = isset( $_GET['s'] ) ? sanitize_text_field( wp_unslash( $_GET['s'] ) ) : '';
		$tipo   = isset( $_GET['media_tipo'] ) ? sanitize_key( wp_unslash( $_GET['media_tipo'] ) ) : 'all';
		// phpcs:enable WordPress.Security.NonceVerification.Recommended
		if ( '' === $search && ( 'all' === $tipo || '' === $tipo ) ) {
			return array_values( $rows );
		}
		$out = array();
		foreach ( $rows as $r ) {
			$file = $this->media_row_file( $r, $kind );
			if ( '' !== $search && false === stripos( $file, $search ) ) {
				continue;
			}
			if ( 'all' !== $tipo && '' !== $tipo && strtolower( pathinfo( $file, PATHINFO_EXTENSION ) ) !== $tipo ) {
				continue;
			}
			$out[] = $r;
		}
		return $out;
	}

